def extract(path):
    return "\n".join(page.extract_text() or "" for page in PdfReader(str(path)).pages)


def test_simple_estimate_generates_selectable_pdf(tmp_path, saved_estimate):
    path = tmp_path / "EST-0042.pdf"
    settings = {
        "company_name": "Must Not Appear Ltd",
        "company_address": "Wrong Settings Address",
        "company_gstin": "GST-CONTACT-1",
        "company_mobile": "9000000001",
        "company_phone": "9000000002",
        "company_email": "contact@example.test",
        "quotation_terms": "Delivery as agreed",
        "bank_account_name": "Universal Agrico",
        "bank_name": "Sample Bank",
        "bank_account_number": "1234567890",
        "bank_branch": "Shornur",
        "bank_ifsc": "BANK0001234",
    }
    QuotationPdfService.generate(saved_estimate, settings, path)
    assert path.is_file() and path.stat().st_size > 0
    body = extract(path)
    page = PdfReader(str(path)).pages[0]
    assert float(page.mediabox.width) == pytest.approx(A4[0])
    assert float(page.mediabox.height) == pytest.approx(A4[1])
    assert float(page.mediabox.width) < float(page.mediabox.height)
    assert "EST-0042" in body and "Sreejith Works" in body
    assert "UNIVERSAL AGRICO" in body
    assert "SIDCO INDUSTRIAL ESTATE" in body
    assert "KULAPPULLY,SHORNUR-2" in body
    assert "PALAKKAD" in body
    assert "GST-CONTACT-1" in body and "9000000001" in body
    assert "9000000002" in body and "contact@example.test" in body
    assert "03/10/2026" in body and "09/04/2025" not in body
    assert "Sreejith Works" in body and "Shornur, Palakkad" in body
    assert "Phone :" in body and "9876500000" in body
    assert "Mild Steel 3 mm" in body
    table_headers = [
        "Sl No", "Material", "Material Rate", "Cutting Rate",
        "Rate Per Unit", "Quantity", "Total Rate",
    ]
    header_positions = [body.index(label) for label in table_headers]
    assert header_positions == sorted(header_positions)
    assert body.count("Total Rate") == 1
    assert "Cutting Time" not in body and "Kilo Rate" not in body
    assert "Weight Calculated" not in body and "Kilo Amount" not in body
    assert "Component" not in body and "Details / Basis" not in body
    assert "32 sq.ft" not in body and "330.00 / sq.ft" not in body
    assert "Rs. 10,560.00" in body
    assert "Must Not Appear Ltd" not in body
    assert "Wrong Settings Address" not in body
    assert "GSTIN:" not in body  # No customer GST field.
    assert "Generated by :" in body and "Anand" in body
    assert "ACCOUNT NAME: Universal Agrico" in body
    assert "BANK NAME: Sample Bank" in body
    assert "ACC NO: 1234567890" in body
    assert "BRANCH NAME: Shornur" in body
    assert "IFSC CODE: BANK0001234" in body
    assert "FOR UNIVERSAL AGRICO" in body
    assert "Authorised signatory" in body
    assert body.index("Generated by :") < body.index("FOR UNIVERSAL AGRICO") < body.index("Authorised signatory")
    assert "Simple Cutting" not in body and "Design Heavy" not in body


def test_design_heavy_estimate_generates_and_uses_saved_values(tmp_path, saved_estimate):
    saved_estimate.calculation_mode = "design_heavy"
    saved_estimate.material = "Stainless Steel"
    saved_estimate.thickness = 2.5
    saved_estimate.sheet_weight = 25
    saved_estimate.kilo_rate = 300
