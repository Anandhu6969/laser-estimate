    assert "5" in body
    assert "Rs. 7,400.00" in body
    assert "Rs. 37,000.00" in body
    assert "Kilo Rate" not in body and "Weight Calculated" not in body
    assert "Kilo Amount" not in body and "Cutting Time" not in body
    assert "GST-OLD" in body
    assert "Air" not in body and "Oxygen" not in body and "Custom" not in body
    assert "Component" not in body and "Details / Basis" not in body


